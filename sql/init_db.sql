SET NAMES utf8mb4;

CREATE DATABASE IF NOT EXISTS cine_paradiso
	CHARACTER SET utf8mb4
	COLLATE utf8mb4_unicode_ci;

USE cine_paradiso;

CREATE TABLE IF NOT EXISTS locales(
id_local INT AUTO_INCREMENT PRIMARY_KEY,
nombre VARCHAR(50) NOT NULL UNIQUE,
direccion VARCHAR(200) NOT NULL UNIQUE,
activo  BOOLEAN NOT NULL DEFAULT TRUE)
CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS salas(
id_sala INT AUTO_INCREMENTAL PRIMARY_KEY,
id_local INT NOT NULL UNIQUE,
numero_sala INT NOT NULL UNIQUE,
capacidad INT NOT NULL,
estado BOOLEAN NOT NULL DEFAULT TRUE,
FOREIGN KEY(id_local) REFERENCES locales(id_local)
)CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    email VARCHAR(200) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    rol ENUM('cliente', 'administrador') NOT NULL DEFAULT 'cliente',
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
)CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;



